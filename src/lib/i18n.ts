export type TranslationKey = keyof typeof translations.en

export function translate(language: Language, key: TranslationKey, values?: Record<string, string | number>) {
  let value = translations[language][key] ?? translations.en[key]

  if (values) {
    for (const [name, replacement] of Object.entries(values)) {
      value = value.replace(`{${name}}`, String(replacement)) as typeof value
    }
  }

  return value
}
